#include "output.h"

void printInt(int a) {
	printf("You entered the integer: %d\n", a);
}

void printInt2(int a, int b) {
	printf("You entered the integer: %d %d\n", a, b);
}

void printFloat(float a) {
	printf("You entered the float: %.2f\n", a);
}

void printFloat2(float a, float b) {
	printf("You entered the float: %.2f %.2f\n", a, b);
}

void printChar(char a) {
	printf("You entered the character: %c\n", a);
}

void printChar2(char a, char b) {
	printf("You entered the character: %c %c\n", a, b);
}